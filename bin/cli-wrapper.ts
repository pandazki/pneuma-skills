/**
 * PNEUMA_CLI wrapper — one spaceless executable path for agent shells.
 *
 * The agent-facing contract is `$PNEUMA_CLI <subcommand> …`. Historically the
 * env var carried the two-token string `bun /path/to/pneuma.ts`, which only
 * ever worked by a coincidence of shell semantics: bash happens to word-split
 * an unquoted expansion, fish NEVER word-splits a variable (the whole string
 * becomes the command name → exit 127), and once the entry path contains a
 * space — the desktop bundle lives under `/Applications/Pneuma Skills.app/…`
 * — bash splits the path itself, and quoting cannot save it either
 * (`"$PNEUMA_CLI"` is one word → 127 again). Two tokens in one env var cannot
 * be invoked correctly across shells, period.
 *
 * The fix: write a tiny `sh` wrapper at a spaceless location
 * (`~/.pneuma/bin/pneuma-<hash>`) that execs the real runtime + entry with
 * both paths quoted INSIDE the script, and hand the agent that single path.
 * One token — correct in bash, zsh and fish, quoted or not, no shell
 * discipline required of the agent.
 *
 * The wrapper is keyed by a content hash of (runtime, entry) so concurrent
 * sessions from different installs (dev worktree vs npm global vs desktop
 * bundle) each keep their own wrapper instead of fighting over one file.
 */

import { mkdirSync, writeFileSync, readFileSync, chmodSync, renameSync, existsSync } from "node:fs";
import { join } from "node:path";
import { homedir } from "node:os";
import { createHash } from "node:crypto";

/** Escape a path for interpolation inside sh double quotes. */
function shDoubleQuote(path: string): string {
  return `"${path.replace(/([\\"$`])/g, "\\$1")}"`;
}

/** The wrapper script body. Exported for tests. */
export function buildWrapperScript(runtime: string, entry: string): string {
  return [
    "#!/bin/sh",
    "# Auto-generated by Pneuma; regenerated at session boot. Do not edit.",
    `exec ${shDoubleQuote(runtime)} ${shDoubleQuote(entry)} "$@"`,
    "",
  ].join("\n");
}

/**
 * The pre-wrapper invocation string, kept as the fallback when the wrapper
 * cannot be written (read-only HOME, exotic sandbox). It retains the old
 * behavior — works under bash with a spaceless entry path — so a degraded
 * environment is no worse off than before.
 */
export function legacyCliInvocation(entry: string): string {
  return `bun ${entry}`;
}

export interface EnsureCliWrapperOptions {
  /** Absolute path of the runtime to exec (default: this process's bun). */
  runtime?: string;
  /** Absolute path of the CLI entry script (bin/pneuma.ts). */
  entry: string;
}

/**
 * Ensure the wrapper exists for this (runtime, entry) pair and return the
 * value to publish as PNEUMA_CLI. Falls back to the legacy two-token string
 * when the wrapper cannot be written; Windows always takes the fallback
 * (a `.cmd` shim is a separate follow-up — the desktop bundle ships for
 * macOS, and POSIX shells are where the contract was broken).
 */
export function ensureCliWrapper(opts: EnsureCliWrapperOptions): string {
  const runtime = opts.runtime ?? process.execPath;
  const entry = opts.entry;
  if (process.platform === "win32") return legacyCliInvocation(entry);

  try {
    // env-first so tests (and sandboxes) can redirect HOME — Bun caches
    // os.homedir() at startup, so the env var is the only live source.
    const home = process.env.HOME ?? process.env.USERPROFILE ?? homedir();
    const binDir = join(home, ".pneuma", "bin");
    const hash = createHash("sha256").update(`${runtime}\n${entry}`).digest("hex").slice(0, 10);
    const wrapperPath = join(binDir, `pneuma-${hash}`);
    const script = buildWrapperScript(runtime, entry);

    if (existsSync(wrapperPath) && readFileSync(wrapperPath, "utf-8") === script) {
      return wrapperPath;
    }

    mkdirSync(binDir, { recursive: true });
    // Write-then-rename so a concurrent boot of the same install never
    // observes a half-written script; chmod before the rename so the file
    // is executable from the instant it appears under its final name.
    const tmpPath = `${wrapperPath}.tmp.${process.pid}`;
    writeFileSync(tmpPath, script, "utf-8");
    chmodSync(tmpPath, 0o755);
    renameSync(tmpPath, wrapperPath);
    return wrapperPath;
  } catch {
    return legacyCliInvocation(entry);
  }
}
